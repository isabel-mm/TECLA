"""
TECLA – TBX Export
------------------

Exports a terminological inventory to TBX-Basic format (ISO 30042).
TBX is the standard interchange format for terminology data and is
supported by tools such as SDL MultiTerm, Terminator, and OmegaT.
"""

import xml.etree.ElementTree as ET
from pathlib import Path
from typing import List, Dict, Any


def export_tbx(
    terms: List[Dict[str, Any]],
    output_path: str,
    language: str,
    title: str = "TECLA Terminology Export",
) -> None:
    """
    Export extracted terms to a TBX-Basic file.

    Parameters
    ----------
    terms : list of dict
        Consolidated term list as returned by HybridTermExtractor.extract().
    output_path : str
        Path to the output .tbx file.
    language : str
        ISO 639-1 language code (e.g. 'en', 'es').
    title : str
        Title embedded in the TBX header.
    """

    root = ET.Element("TBX", attrib={
        "type": "TBX-Basic",
        "xml:lang": language,
        "xmlns": "urn:iso:std:iso:30042:ed-2",
    })

    # --- Header ---
    header = ET.SubElement(root, "tbxHeader")
    file_desc = ET.SubElement(header, "fileDesc")
    title_stmt = ET.SubElement(file_desc, "titleStmt")
    title_el = ET.SubElement(title_stmt, "title")
    title_el.text = title

    source_desc = ET.SubElement(file_desc, "sourceDesc")
    source_p = ET.SubElement(source_desc, "p")
    source_p.text = "Generated by TECLA – Term Extraction and Corpus Linguistics Application"

    # --- Body ---
    text_el = ET.SubElement(root, "text")
    body = ET.SubElement(text_el, "body")

    for i, term in enumerate(terms, start=1):
        concept = ET.SubElement(body, "conceptEntry", attrib={"id": f"c{i}"})
        lang_sec = ET.SubElement(concept, "langSec", attrib={"xml:lang": language})
        term_sec = ET.SubElement(lang_sec, "termSec")

        term_el = ET.SubElement(term_sec, "term")
        term_el.text = term.get("term", "")

        _add_note(term_sec, "termType", "fullForm")
        _add_note(term_sec, "frequency", str(term.get("frequency", "")))
        _add_note(term_sec, "cValue", f"{term.get('c_value', 0.0):.4f}")
        _add_note(term_sec, "ncValue", f"{term.get('nc_value', 0.0):.4f}")
        _add_note(term_sec, "terminologicity", f"{term.get('terminologicity', 0.0):.4f}")

        if term.get("patterns"):
            patterns_val = (
                ";".join(term["patterns"])
                if isinstance(term["patterns"], list)
                else str(term["patterns"])
            )
            _add_note(term_sec, "grammaticalPatterns", patterns_val)

        # Variant forms — each gets its own <termSec> with termType=variant
        for variant_surface in term.get("variants", []):
            var_sec = ET.SubElement(lang_sec, "termSec")
            var_el  = ET.SubElement(var_sec, "term")
            var_el.text = variant_surface
            _add_note(var_sec, "termType", "variant")

    # --- Write ---
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    tree = ET.ElementTree(root)
    ET.indent(tree, space="  ")

    with open(output_path, "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n')
        tree.write(f, encoding="unicode", xml_declaration=False)

    print(f"✅ TBX export written to '{output_path}' ({len(terms)} terms)")


def _add_note(parent: ET.Element, note_type: str, value: str) -> None:
    """Append a <termNote> element to a termSec."""
    note = ET.SubElement(parent, "termNote", attrib={"type": note_type})
    note.text = value
